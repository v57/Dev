import Foundation

// MARK: - Error

enum StringCatalogError: LocalizedError {
  case unreadable(URL, Error)
  case undecodable(URL, Error)

  var errorDescription: String? {
    switch self {
    case .unreadable(let url, let error):
      return "Couldn't read \(url.path): \(error.localizedDescription)"
    case .undecodable(let url, let error):
      return "Couldn't parse \(url.lastPathComponent): \(error.localizedDescription)"
    }
  }
}

// MARK: - StringCatalog

/// Lossless Codable mirror of an .xcstrings file. One type for the whole
/// format, so a future schema change is a single-file fix.
/// `nonisolated`: pure value type with no shared state — the scan engine
/// merges into it off the main actor.
nonisolated struct StringCatalog: Codable, Sendable {
  /// BCP-47 language code the keys are authored in ("en" for this fixture).
  var sourceLanguage: String
  /// Format version ("1.1"). Optional: version 1.0 catalogs omit it.
  var version: String?
  /// JSON object keyed by the string keys themselves (empty keys are legal),
  /// decoded as a dictionary — never an array.
  var strings: [String: Entry]

  // MARK: entry shapes

  struct Entry: Codable, Sendable {
    var localizations: [String: Language]?
    var comment: String?
    var extractionState: String?
    var shouldTranslate: Bool?
    var isCommentAutoGenerated: Bool?
  }

  struct Language: Codable, Sendable {
    /// The plain single-form translation, when the entry is not varied.
    var stringUnit: StringUnit?
    /// Plural/device variations, keyed by variation type ("plural", "device")
    /// and then by rule/trait ("one", "other", "iphone", …). Tolerated
    /// losslessly; Phase A never edits them.
    var variations: [String: [String: VariationUnit]]?
    /// Multi-argument format-string substitutions (`"%#@a@"` + a per-argument
    /// spec), keyed by argument name. Tolerated losslessly — an edit through
    /// a flat cell leaves them in place, and dropping them would silently
    /// destroy a real catalog's argument plurals.
    var substitutions: [String: Substitution]?

    /// True when the node carries nothing to write — no flat unit, no
    /// variation rule with content and no substitution arguments. Xcode's
    /// compiler rejects a bare localization node, so such an entry is dropped
    /// on the way to disk (see `StringCatalog.normalizeForWrite`).
    var isEmptySlot: Bool {
      if stringUnit != nil { return false }
      if let substitutions, !substitutions.isEmpty { return false }
      return variations?.values.allSatisfy(\.isEmpty) ?? true
    }
  }

  /// One `substitutions` argument: the format specifier plus its own
  /// variation tree (e.g. `plural` per CLDR category).
  struct Substitution: Codable, Sendable {
    /// Which format argument this substitution stands for (1-based). Xcode
    /// writes it whenever a string has more than one argument; without it the
    /// arguments bind by order, which is wrong as soon as a translation
    /// reorders them.
    var argNum: Int?
    var formatSpecifier: String?
    var variations: [String: [String: VariationUnit]]?
  }

  /// One case of a variation: either a leaf (`stringUnit`) or a further
  /// variation tree — Xcode nests them, e.g. `device` → `iphone` → `plural`.
  struct VariationUnit: Codable, Sendable {
    var stringUnit: StringUnit?
    /// A nested variation under this case. Tolerated losslessly, like
    /// `substitutions`: nothing here edits it, and dropping it would leave a
    /// bare `"iphone" : { }` that Xcode's compiler rejects.
    var variations: [String: [String: VariationUnit]]?
  }

  struct StringUnit: Codable, Sendable {
    /// "needs_review" / "translated" / "new" / … — kept raw, never normalized.
    var state: String?
    var value: String?
  }

  // MARK: - loading

  static func load(url: URL) throws -> StringCatalog {
    let data: Data
    do {
      data = try Data(contentsOf: url)
    } catch {
      throw StringCatalogError.unreadable(url, error)
    }
    do {
      return try JSONDecoder().decode(StringCatalog.self, from: data)
    } catch {
      throw StringCatalogError.undecodable(url, error)
    }
  }

  /// Decodes `url` genuinely OFF the main actor, for the store's open/reload.
  ///
  /// `load(url:)` is a synchronous function: called from the store — whose
  /// every method is MainActor-isolated, because this target builds with
  /// `SWIFT_DEFAULT_ACTOR_ISOLATION = MainActor` — the decode runs ON the
  /// main thread. Wrapping the call in `await MainActor.run { … }` does NOT
  /// change that: the hop is to the actor the caller is already on, so the
  /// parse still blocks the UI (measured 96 ms for a 7 MB / 1382-key
  /// catalog — noticeable on a big file, but not the freeze that matters).
  /// Only a detached task actually moves it off.
  nonisolated static func loadOffMainActor(
    _ url: URL, priority: TaskPriority = .userInitiated
  ) async -> Result<StringCatalog, Error> {
    await Task.detached(priority: priority) {
      do { return .success(try load(url: url)) } catch { return .failure(error) }
    }.value
  }

  // MARK: - UI-facing helpers

  /// Every language referenced by the catalog (any localization) plus the
  /// source language, sorted ascending.
  var languages: [String] {
    var seen = Set<String>()
    for entry in strings.values {
      if let localizations = entry.localizations {
        seen.formUnion(localizations.keys)
      }
    }
    seen.insert(sourceLanguage)
    return seen.sorted()
  }

  func entry(for key: String) -> Entry? {
    strings[key]
  }

  /// Raw parsed value for a key/language pair, or nil when the file has none.
  func rawValue(for key: String, language: String) -> String? {
    strings[key]?.localizations?[language]?.stringUnit?.value
  }

  /// Parsed translation state ("needs_review" / "translated" / "new" / …), or nil.
  func state(for key: String, language: String) -> String? {
    strings[key]?.localizations?[language]?.stringUnit?.state
  }

  /// True when the file carries a stringUnit for this key/language (even an empty one).
  func hasValue(for key: String, language: String) -> Bool {
    strings[key]?.localizations?[language]?.stringUnit != nil
  }

  /// Source-language display rule: explicit source stringUnit when present,
  /// else the key text itself (the catalog convention).
  func sourceDisplay(for key: String) -> String {
    rawValue(for: key, language: sourceLanguage) ?? key
  }

  /// True when any language entry of this key carries variations.
  func hasVariations(for key: String) -> Bool {
    guard let localizations = strings[key]?.localizations else { return false }
    return localizations.values.contains { $0.variations?.isEmpty == false }
  }

  /// True when any language entry of this key carries a *plural* variation.
  /// Device variations do not count — they stay read-only.
  func hasPlurals(for key: String) -> Bool {
    guard let localizations = strings[key]?.localizations else { return false }
    return localizations.values.contains { $0.variations?["plural"]?.isEmpty == false }
  }

  /// True when this key/language slot carries a plural variation.
  func hasPlurals(for key: String, language: String) -> Bool {
    strings[key]?.localizations?[language]?.variations?["plural"]?.isEmpty == false
  }

  /// True when this key/language slot carries a non-plural (device) variation.
  /// Device slots stay read-only everywhere.
  func hasDeviceVariations(for key: String, language: String) -> Bool {
    guard let variations = strings[key]?.localizations?[language]?.variations else { return false }
    return variations.keys.contains { $0 != "plural" }
  }

  /// Plural form values for a key/language pair: category -> stringUnit.
  /// Nil when the slot has no plural variation.
  func pluralUnits(for key: String, language: String) -> [String: StringUnit]? {
    let plural = strings[key]?.localizations?[language]?.variations?["plural"]
    guard let plural, !plural.isEmpty else { return nil }
    var units: [String: StringUnit] = [:]
    for (category, variation) in plural {
      if let unit = variation.stringUnit {
        units[category] = unit
      }
    }
    return units.isEmpty ? nil : units
  }

  /// Raw parsed value of one plural form, or nil when the form is absent.
  func pluralValue(for key: String, language: String, category: String) -> String? {
    strings[key]?.localizations?[language]?.variations?["plural"]?[category]?.stringUnit?.value
  }

  /// Parsed state of one plural form, or nil.
  func pluralState(for key: String, language: String, category: String) -> String? {
    strings[key]?.localizations?[language]?.variations?["plural"]?[category]?.stringUnit?.state
  }

  /// All plural form values of the source language for a key (category ->
  /// value), for AI reference prompts. Empty when the source is not varied.
  func sourcePluralForms(for key: String) -> [String: String] {
    guard let units = pluralUnits(for: key, language: sourceLanguage) else { return [:] }
    var forms: [String: String] = [:]
    for (category, unit) in units {
      if let value = unit.value, !value.isEmpty {
        forms[category] = value
      }
    }
    return forms
  }

  /// Source display text for one plural form: the source form itself, else
  /// the source "other" form, else the key text (the catalog convention).
  func sourcePluralDisplay(for key: String, category: String) -> String {
    if let value = pluralValue(for: key, language: sourceLanguage, category: category),
       !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      return value
    }
    if category != "other",
       let other = pluralValue(for: key, language: sourceLanguage, category: "other"),
       !other.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      return other
    }
    return sourceDisplay(for: key)
  }

  // MARK: - plural mutations

  /// "Vary by plural": gives each listed language a plural variation with the
  /// CLDR categories of that language. A flat stringUnit value/state moves
  /// into the "other" form (every CLDR set has "other"); the flat unit is
  /// removed. Missing forms stay absent — records model them as empty slots
  /// the pipeline fills. Languages already varied are left untouched.
  mutating func varyByPlural(key: String, languages: [String]) {
    guard var entry = strings[key], entry.shouldTranslate != false else { return }
    for language in languages {
      if hasPlurals(for: key, language: language) { continue }
      var localizations = entry.localizations ?? [:]
      var loc = localizations[language] ?? Language()
      let flat = loc.stringUnit
      var plural: [String: VariationUnit] = [:]
      for category in PluralRules.categories(for: language) {
        if category == "other", let flat, let value = flat.value {
          plural[category] = VariationUnit(stringUnit: StringUnit(state: flat.state, value: value))
        } else {
          // Skeleton form: no stringUnit yet (absence IS empty). Keeps the
          // variation non-empty so hasPlurals() is true for the new shape.
          plural[category] = VariationUnit()
        }
      }
      var variations = loc.variations ?? [:]
      variations["plural"] = plural
      loc.variations = variations
      loc.stringUnit = nil
      localizations[language] = loc
      entry.localizations = localizations
    }
    strings[key] = entry
  }

  /// Adds an empty localization slot for `language` to every key that lacks
  /// one (a unit-less entry — no stringUnit, no variations). The language then
  /// appears in `languages`, which is what the plural-skeleton passes read.
  /// Returns how many keys gained the slot.
  ///
  /// In-memory only, and deliberately so: a node with no content is a BARE
  /// localization entry, which Xcode's compiler rejects, so `normalizeForWrite`
  /// prunes these on the way to disk. The file therefore gains a language only
  /// where a translation exists to write; the app keeps an added language
  /// visible through the records it seeds (`Reconcile.addLanguage`), which is
  /// also what makes it survive a reopen — see
  /// `LocalizationStore.browserLanguages`.
  @discardableResult
  mutating func addLanguage(_ language: String) -> Int {
    var added = 0
    for key in strings.keys {
      guard var entry = strings[key] else { continue }
      var localizations = entry.localizations ?? [:]
      if localizations[language] == nil {
        localizations[language] = Language()
        entry.localizations = localizations
        strings[key] = entry
        added += 1
      }
    }
    return added
  }

  /// Collapses a key's plural variations back to a flat stringUnit per
  /// language (the "other" form's value/state wins, else the first filled
  /// form). Used by "Remove plural variations".
  mutating func removePlurals(key: String) {
    guard var entry = strings[key] else { return }
    guard var localizations = entry.localizations else { return }
    for (language, var loc) in localizations {
      guard var variations = loc.variations, variations["plural"] != nil else { continue }
      let plural = variations["plural"] ?? [:]
      let ordered = (["other"] + plural.keys.sorted()).uniqued()
      var winner: StringUnit?
      for category in ordered {
        if let unit = plural[category]?.stringUnit, unit.value != nil {
          winner = unit
          break
        }
      }
      variations.removeValue(forKey: "plural")
      loc.variations = variations.isEmpty ? nil : variations
      if loc.stringUnit == nil {
        loc.stringUnit = winner
      }
      localizations[language] = loc
    }
    entry.localizations = localizations
    strings[key] = entry
  }

  /// Collapses ONE language's plural variation for `key` back to a flat stringUnit ("other" wins,
  /// else the first filled form) and drops the variation. The language-scoped half of
  /// `removePlurals(key:)`: a load that follows a reviewed FLAT value has to be able to flatten the
  /// file's slot for that language without touching the key's other languages (which may well be
  /// legitimately plural).
  mutating func flatten(key: String, language: String) {
    guard var entry = strings[key], var localizations = entry.localizations,
          var loc = localizations[language], var variations = loc.variations,
          let plural = variations["plural"]
    else { return }
    let ordered = (["other"] + plural.keys.sorted()).uniqued()
    var winner: StringUnit?
    for category in ordered {
      if let unit = plural[category]?.stringUnit, unit.value != nil {
        winner = unit
        break
      }
    }
    variations.removeValue(forKey: "plural")
    loc.variations = variations.isEmpty ? nil : variations
    if loc.stringUnit == nil {
      loc.stringUnit = winner
    }
    localizations[language] = loc
    entry.localizations = localizations
    strings[key] = entry
  }

  /// Sets one plural form's value/state, creating the variation skeleton as
  /// needed. Empty text removes the form's stringUnit (absence IS empty).
  mutating func setPluralValue(_ text: String, state: String?, key: String, language: String, category: String) {
    guard var entry = strings[key] else { return }
    var localizations = entry.localizations ?? [:]
    var loc = localizations[language] ?? Language()
    var variations = loc.variations ?? [:]
    var plural = variations["plural"] ?? [:]
    if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      var unit = plural[category] ?? VariationUnit()
      unit.stringUnit = nil
      plural[category] = unit
    } else {
      plural[category] = VariationUnit(stringUnit: StringUnit(state: state, value: text))
    }
    variations["plural"] = plural
    loc.variations = variations
    localizations[language] = loc
    entry.localizations = localizations
    strings[key] = entry
  }

  /// Sets a source-language plural form directly (source has no DB records —
  /// it is authored text, written straight to the file by the caller).
  /// `state` is not optional in the artifact: a unit carrying only a value is
  /// rejected by Xcode's compiler ("Missing required key 'state'"), so the
  /// form inherits the entry's existing source state and falls back to "new".
  mutating func setSourcePluralValue(_ text: String, key: String, category: String) {
    setPluralValue(
      text, state: sourceUnitState(for: key), key: key,
      language: sourceLanguage, category: category)
  }

  /// State a freshly written source form should carry: the entry's own source
  /// unit state, else the source "other" form's, else "new" (what Xcode
  /// writes for authored source text).
  private func sourceUnitState(for key: String) -> String {
    let loc = strings[key]?.localizations?[sourceLanguage]
    if let state = loc?.stringUnit?.state { return state }
    for category in ["other"] + PluralRules.categories(for: sourceLanguage) {
      if let state = loc?.variations?["plural"]?[category]?.stringUnit?.state { return state }
    }
    return "new"
  }

  // MARK: - saving

  /// Atomically encodes the catalog back to its file. Shared by the
  /// record-commit path and the direct source-plural writes — and this is
  /// where the artifact is guaranteed to COMPILE: the model is normalized
  /// first (see `normalizeForWrite`), because two shapes it can legitimately
  /// hold in memory are hard errors for Xcode's compiler while every JSON
  /// parser accepts them.
  func save(to url: URL) throws {
    var outgoing = self
    if needsWriteNormalization {
      outgoing.normalizeForWrite()
    }
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    let data = try encoder.encode(outgoing)
    try data.write(to: url, options: .atomic)
  }

  /// True when at least one unit would change on the way out. Read-only, so a
  /// clean catalog encodes straight from `self` — no copy, and a save that
  /// changes nothing stays byte-identical.
  var needsWriteNormalization: Bool {
    for entry in strings.values {
      guard let localizations = entry.localizations else { continue }
      for (language, loc) in localizations
      where normalized(loc, language: language).changed || loc.isEmptySlot {
        return true
      }
    }
    return false
  }

  /// In-place `normalized` for the whole catalog, on the way to disk. Nodes
  /// left with nothing are dropped: Xcode's compiler rejects a bare
  /// `"de" : { }` localization entry too. A language whose only content was
  /// empty form skeletons therefore leaves the FILE (the in-memory catalog
  /// keeps it — the UI is unaffected until a reload — and adding the language
  /// again is the user's explicit action through `addLanguage`, which the
  /// per-key records survive in all cases).
  mutating func normalizeForWrite() {
    for key in strings.keys {
      guard var entry = strings[key], var localizations = entry.localizations else { continue }
      for language in Array(localizations.keys) {
        guard let loc = localizations[language] else { continue }
        let repaired = normalized(loc, language: language)
        if repaired.slot.isEmptySlot {
          localizations.removeValue(forKey: language)
        } else if repaired.changed {
          localizations[language] = repaired.slot
        }
      }
      entry.localizations = localizations.isEmpty ? nil : localizations
      strings[key] = entry
    }
  }

  /// One localization node as it should reach the file: every unit either
  /// carries a complete stringUnit or is gone. Two shapes are dropped —
  ///
  ///   - `"one" : { }`, the skeleton form `varyByPlural` / `setPluralValue`
  ///     create so `hasPlurals()` reads true while a run fills them. On disk a
  ///     form is EITHER present with a value OR absent, the same rule flat
  ///     slots follow ("Missing required key 'stringUnit'" otherwise).
  ///   - a unit with no `state` at all ("Missing required key 'state'") —
  ///     what the source-form write path used to produce.
  ///
  /// A unit that kept its state but lost the value gets `value: ""` (Xcode's
  /// own shape for a string that exists untranslated); a unit that kept a
  /// value but lost the state gets `defaultState(for:)`. Device variations
  /// and `substitutions` argument trees are never touched: this phase does not
  /// write them, and inventing a shape for a dropped argument is worse than
  /// carrying it through.
  private func normalized(_ loc: Language, language: String) -> (slot: Language, changed: Bool) {
    var slot = loc
    var changed = false

    if let unit = slot.stringUnit {
      if unit.state == nil, unit.value == nil {
        slot.stringUnit = nil                          // nothing to write — absent
        changed = true
      } else if unit.state == nil || unit.value == nil {
        var repaired = unit
        if repaired.value == nil { repaired.value = "" }
        if repaired.state == nil { repaired.state = defaultState(for: language) }
        slot.stringUnit = repaired
        changed = true
      }
    }

    if var variations = slot.variations, var plural = variations["plural"] {
      for category in Array(plural.keys) {
        guard let unit = plural[category]?.stringUnit else {
          plural.removeValue(forKey: category)         // skeleton — absence IS empty
          changed = true
          continue
        }
        if unit.state == nil, unit.value == nil {
          plural.removeValue(forKey: category)         // `"stringUnit" : { }`
          changed = true
        } else if unit.state == nil || unit.value == nil {
          var repaired = unit
          if repaired.value == nil { repaired.value = "" }
          if repaired.state == nil { repaired.state = defaultState(for: language) }
          plural[category] = VariationUnit(stringUnit: repaired)
          changed = true
        }
      }
      if plural.isEmpty {
        variations.removeValue(forKey: "plural")       // an empty plural is no plural
        changed = true
      } else {
        variations["plural"] = plural
      }
      slot.variations = variations.isEmpty ? nil : variations
    }

    return (slot, changed)
  }

  /// State a repaired unit gets when it carries none. The source language
  /// holds authored text, so "new" (what Xcode writes for it); anything else
  /// can only be machine output here and lands in the needs_review bucket the
  /// pipeline uses.
  private func defaultState(for language: String) -> String {
    language == sourceLanguage ? "new" : "needs_review"
  }
}

// MARK: - PluralRules

/// The plural categories a language's variation template carries.
///
/// The table below is Xcode's OWN, extracted from
/// `/Applications/Xcode.app/Contents/SharedFrameworks/XCStringsParser.framework/Versions/A/Resources/variationConfigFile.plist`
/// (`PluralRule.ComplementedPluralKeys`, 161 bare locales), keeping only the
/// languages whose set differs from the ubiquitous `one`/`other` — the
/// `default` below is exactly that pair, so any code the table does not name
/// still gets a correct template. Regenerate the same way when the Add
/// Language set grows; never hand-write these from memory (three of the
/// pre-12-Sep entries did: `cs`/`sk` were missing `many`, `hr`/`sr` an extra
/// `many`, and `fr`/`pt` an extra `many`, all against Xcode's own data).
///
/// Three locales Xcode ships NO template for are filled from CLDR instead, and
/// are called out where they appear: `ars` (Arabic rules), `sa` and `sat`
/// (one/two/other). They are keyboard-only languages; getting them wrong would
/// silently create or drop a form, and nothing downstream would catch it —
/// `xcstringstool` accepts any category for any locale (probed).
nonisolated enum PluralRules {
  /// Languages whose plural set is not the default `["one", "other"]`.
  private static let nonDefault: [String: [String]] = [
    "ar": ["zero", "one", "two", "few", "many", "other"], "be": ["one", "few", "many", "other"],
    "bm": ["other"], "bo": ["other"],
    "br": ["one", "two", "few", "many", "other"], "bs": ["one", "few", "other"],
    "cs": ["one", "few", "many", "other"], "cy": ["zero", "one", "two", "few", "many", "other"],
    "dsb": ["one", "two", "few", "other"], "dz": ["other"],
    "ga": ["one", "two", "few", "many", "other"], "gd": ["one", "two", "few", "other"],
    "gv": ["one", "two", "few", "many", "other"], "he": ["one", "two", "many", "other"],
    "hr": ["one", "few", "other"], "hsb": ["one", "two", "few", "other"],
    "id": ["other"], "ig": ["other"],
    "ii": ["other"], "iu": ["one", "two", "other"],
    "ja": ["other"], "kde": ["other"],
    "kea": ["other"], "km": ["other"],
    "ko": ["other"], "ksh": ["zero", "one", "other"],
    "kw": ["one", "two", "other"], "lag": ["zero", "one", "other"],
    "lkt": ["other"], "lo": ["other"],
    "lt": ["one", "few", "many", "other"], "lv": ["zero", "one", "other"],
    "ms": ["other"], "mt": ["one", "few", "many", "other"],
    "my": ["other"], "naq": ["one", "two", "other"],
    "pl": ["one", "few", "many", "other"], "ro": ["one", "few", "other"],
    "ru": ["one", "few", "many", "other"], "sah": ["other"],
    "se": ["one", "two", "other"], "ses": ["other"],
    "sg": ["other"], "shi": ["one", "few", "other"],
    "sk": ["one", "few", "many", "other"], "sl": ["one", "two", "few", "other"],
    "smn": ["one", "two", "other"], "sr": ["one", "few", "other"],
    "th": ["other"], "to": ["other"],
    "uk": ["one", "few", "many", "other"], "vi": ["other"],
    "yo": ["other"], "yue": ["other"],
    "zh": ["other"],
    // CLDR, because Xcode's table has no entry for these three at all.
    "ars": ["zero", "one", "two", "few", "many", "other"],
    "sa": ["one", "two", "other"],
    "sat": ["one", "two", "other"],
  ]

  static func categories(for language: String) -> [String] {
    let base = language.split(separator: "-").first?.split(separator: "_").first.map(String.init)?.lowercased() ?? language.lowercased()
    return nonDefault[base] ?? ["one", "other"]
  }

  /// Display names for the editor ("one" -> "One").
  static func displayName(for category: String) -> String {
    category.prefix(1).uppercased() + category.dropFirst()
  }
}

// MARK: - private helpers

extension Array where Element: Hashable {
  /// `nonisolated`: a pure array helper. Without it the module's MainActor
  /// default isolation makes this MainActor-only, and the nonisolated
  /// `StringCatalog` cannot call it (a warning today, an error in Swift 6).
  nonisolated func uniqued() -> [Element] {
    var seen = Set<Element>()
    return filter { seen.insert($0).inserted }
  }
}
